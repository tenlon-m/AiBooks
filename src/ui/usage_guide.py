"""使用指南对话框 - 如何通过本程序写一本全本小说的步骤说明."""
from __future__ import annotations

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QDialog,
    QHBoxLayout,
    QLabel,
    QPushButton,
    QTextEdit,
    QVBoxLayout,
    QWidget,
)


GUIDE_TEXT = """\
AiBooks 使用指南 —— 如何写一本全本小说

═══════════════════════════════════════════════════════════════

第一步：配置 AI 模型源（工具 → AI源配置）

  1. 在"AI源配置"页面添加至少一个 AI 模型源。
  2. 在线免费源：选择"在线OpenAI兼容"类型，填写 API 地址和模型名称。
  3. 本地源：选择"本地Ollama"类型，系统自动获取该电脑已安装的模型列表供选择。
  4. 点击"测试连接"确认可用。
  5. 设置路由策略和优先级/权重（见下方说明），保存。

  ── 路由策略说明 ──

  系统支持四种路由策略，决定多模型之间如何选择调用：

  • 故障转移（推荐）：按优先级从小到大依次尝试。优先级数字越小越先调用，
    第一个源调用失败时自动切换到下一个源。此策略下权重不生效。
    适用场景：有主力模型 + 备用模型，主力优先，主力挂了用备用。

  • 负载均衡：按权重比例随机分配请求到各源。权重越大分到的请求越多。
    例如源A权重3、源B权重1，则A分到75%请求、B分到25%。
    此策略下优先级不生效。同权重的源随机选择。
    适用场景：多个模型质量相当，想分散负载避免单源限流。

  • 手动指定：始终使用指定的单一源，不使用优先级和权重。
    适用场景：调试或强制使用某个特定模型。

  • 成本优先：免费/本地源优先调用，付费源兜底。同类内按优先级排序。
    适用场景：优先用免费额度，免费用完再用付费。

  ── 优先级和权重设置示例 ──

  场景一：A模型为常用主力，B/C/本地模型为辅助备用
    → 路由策略设为"故障转移"
    → A模型优先级设为 1（最先调用）
    → B模型优先级设为 2（A失败时用）
    → C模型优先级设为 3（A、B都失败时用）
    → 本地模型优先级设为 4（最后兜底）
    → 权重无需设置（故障转移策略不使用权重）

  场景二：本地模型为常用主力，其他在线模型为辅助备用
    → 路由策略设为"故障转移"
    → 本地模型优先级设为 1（最先调用，免费免Key）
    → A在线模型优先级设为 2（本地失败时用）
    → B在线模型优先级设为 3（本地和A都失败时用）
    → 权重无需设置

  场景三：多个模型质量相当，想分散负载
    → 路由策略设为"负载均衡"
    → 各模型权重按期望分配比例设置
    → 例如三个模型平均分配：权重都设为 1
    → 例如A模型多分一些：A权重3、B权重2、C权重1

  注意：优先级和权重都允许重复。同优先级的源在故障转移策略下
  按列表顺序尝试；同权重的源在负载均衡策略下随机选择。

═══════════════════════════════════════════════════════════════

第二步：设定创作参数（创作参数页）

  1. 输入书名、卷数、每卷章节数、每章字数。
  2. 输入或导入故事梗概（≥50字）—— 全书统一的故事主线。
  3. 输入或导入世界观设定（≥50字）—— 全书统一的世界观。
  4. 点击"创建新项目"，系统生成项目 ID。
  5. 保存梗概和世界观。

═══════════════════════════════════════════════════════════════

第三步：提取与确认人物（人物管理页）

  1. 点击"AI提取人物"，系统根据梗概和世界观自动提取主要人物和配角。
  2. 检查提取结果，手动添加遗漏的人物（填写姓名、身份、简介、关系）。
  3. 如需更多配角，点击"AI生成配角"。
  4. 确认所有人物（选中行 → "确认选中人物"）。

═══════════════════════════════════════════════════════════════

第四步：生成全书大纲（大纲管理页）

  1. 点击"AI整体生成大纲"一次性生成全书，或点击"AI分批生成大纲"
     分批次生成（长篇推荐，每批携带前文衔接上下文）。
  2. 生成过程中可"暂停"，之后点"续写"从断点继续，已完成部分不会丢失。
  3. 点击"校验一致性"检查大纲是否合理，可"一键修复"让 AI 自动处理问题。
  4. 选中章节点"细化场景"，把单章拆成 3-5 个场景（目标/出场角色/关键事件/
     情绪基调/预计字数），也可用"批量细化场景"一次处理多章。
  5. "一键填充出场人物"让 AI 补全每章的出场人物，供后续一致性校验使用。
  6. 双击节点可直接编辑，改完点"保存大纲"；在大纲树上拖拽可调整卷章顺序。

═══════════════════════════════════════════════════════════════

第五步：设计爽点与钩子（爽点钩子页）

  1. 点击"AI逐章生成"，系统根据梗概、世界观、人物和章节大纲
     自动为每章设计爽点（高潮点）和钩子（悬念），并安排钩子回收章节。
  2. 生成过程中可"暂停"/"续写"；重新打开页面会自动检测进度并提示可继续。
  3. 点击"校验一致性"检查基调与回收逻辑，可"一键修复"。
  4. 双击表格行可直接编辑，改完点"保存"。
  5. 每章必有爽点和钩子，钩子将在后续章节自动回收。

═══════════════════════════════════════════════════════════════

第六步：投喂风格库（风格库页）

  1. 选择参考作者的语料文件（txt/md 格式）。
  2. 输入风格库名称，点击"投喂建立"。
  3. 系统自动提取叙事视角、句式、用词、节奏等风格特征。
  4. 查看风格库详情，确认特征准确。
  5. 风格库用于撰写时去 AI 化，使文风贴近真人作者。

═══════════════════════════════════════════════════════════════

第七步：全文批量撰写（撰写进度页）

  1. 在"▼ 撰写思路与风格设置"面板中填写撰写思路，并点"加载风格库"选择风格。
  2. 点击"开始撰写"，系统逐章生成全文，每章完成即时显示。
  3. 撰写过程中可"暂停"，之后点"续写"从断点继续，已完成章节不丢失。
  4. 撰写页还提供：
     • "AI对话" —— 针对选中段落或整章与 AI 讨论（改写/建议/讨论/剧情走向）
     • "查看场景" —— 查看当前章节的场景大纲
     • "生成摘要"/"批量生成摘要" —— 为章节生成摘要
     • "批量查找替换" —— 全书或按范围替换，支持正则
     • 右键 —— 选中段落后可"续写/扩写/缩写"，结果可替换原文或插入到原文后
        （预览区为只读，产生修改后需点"保存"才写入数据库）

═══════════════════════════════════════════════════════════════

第八步：全书校验（校验报告页）

  1. 点击"全书校验"，系统对全书进行综合校验（梗概/世界观/人物/钩子/
     物品/AI化/风格 七个维度），生成问题清单与整体评分。
  2. 检查校验结果：人物一致性、物品一致性、钩子回收、字数达标等。
  3. 查看 AI 化程度评分，评估去 AI 化效果。
  4. 只需重查部分章节时用"批量再校验"（一次最多 50 章）。
  5. 如有问题，进入章节编辑页修改。

═══════════════════════════════════════════════════════════════

第九步：章节编辑与 AI 润色（章节编辑页）

  1. 选择需要修改的章节。
  2. 直接编辑正文内容。
  3. 点击"保存并再校验"，系统保存修改并自动再校验该章。
     （每次保存自动生成版本快照，可随时在"版本管理"中对比或回滚）
  4. 如需润色，点击"AI润色"，系统生成润色版本并排预览。
  5. 查看调整说明，决定"采纳润色"或"拒绝润色"。
  6. 已定稿章节可点"锁定"防止误改；"批注侧栏"可添加/编辑/标记失效批注。
  7. "阅读模式"可按书籍排版预览，支持调整字体、行距与护眼背景。
  8. 重复直到所有章节满意。

═══════════════════════════════════════════════════════════════

第十步：历史回滚（历史回滚页）

  1. 如修改后不满意，可选择章节查看修改历史。
  2. 选中一行会在下方"内容预览"显示该次修改后的正文。
  3. 点击"回滚到选中记录"恢复之前版本，回滚后会展示再校验结果。

═══════════════════════════════════════════════════════════════

第十一步：导出小说（文件 → 导出小说）

  前置条件：项目状态为"已完成"，且全部章节都已生成完成并有正文。
  不满足时导出会失败，请先回到撰写页补齐章节。

  1. 选择导出格式：TXT / DOCX / EPUB / Markdown / PDF。
  2. 选择排版模板：出版风格 / 简洁风格 / 网文风格
     （TXT 为纯文本，不使用排版模板）。
  3. 勾选导出选项：章节分页、包含大纲、包含角色设定、封面页。
  4. 选择导出目录，点击"导出小说"。
  5. 导出完成后可在外部编辑器中查看最终成品。

═══════════════════════════════════════════════════════════════

第十二步：备份与迁移（工具 → 备份管理）

  1. 设置备份策略（定时备份、退出触发、保留份数）。
  2. 可随时手动触发备份。
  3. 支持项目导出为 .aibk 文件，迁移到其他设备。
  4. 通过"导入项目"恢复备份的项目。

═══════════════════════════════════════════════════════════════

温馨提示：
  • 每一步完成后建议检查结果再进入下一步。
  • AI 生成内容可能需要多次修改和润色才能达到理想效果。
  • 定期备份项目，防止数据丢失。
  • 可随时切换 AI 模型源以获得不同的生成风格。
"""


class UsageGuideDialog(QDialog):
    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self.setWindowTitle("使用指南 - 如何写一本全本小说")
        self.setMinimumSize(800, 600)
        self._init_ui()

    def _init_ui(self) -> None:
        layout = QVBoxLayout(self)

        title = QLabel("AiBooks 使用指南")
        title.setStyleSheet("font-size: 20px; font-weight: bold; padding: 8px;")
        title.setAlignment(Qt.AlignmentFlag.AlignCenter)
        layout.addWidget(title)

        text_edit = QTextEdit()
        text_edit.setReadOnly(True)
        text_edit.setPlainText(GUIDE_TEXT)
        text_edit.setStyleSheet("font-size: 13px; line-height: 1.6;")
        layout.addWidget(text_edit, 1)

        close_btn = QPushButton("关闭")
        close_btn.setStyleSheet("padding: 6px 24px;")
        close_btn.clicked.connect(self.accept)
        btn_layout = QHBoxLayout()
        btn_layout.addStretch()
        btn_layout.addWidget(close_btn)
        btn_layout.addStretch()
        layout.addLayout(btn_layout)